// One-off generator for src/data/worldCountryPaths.ts
// Source: world-atlas (Natural Earth 110m, public domain), converted to a flat
// equirectangular SVG path per country, keyed by ISO 3166-1 alpha-2.
//
// Re-run with: node scripts/generate-world-map.js
// (Requires world-atlas, topojson-client, i18n-iso-countries as devDependencies.)

const fs = require('fs');
const path = require('path');
const topojson = require('topojson-client');
const iso = require('i18n-iso-countries');
const topology = require('world-atlas/countries-110m.json');

const DECIMALS = 2;

function round(n) {
  return Math.round(n * 10 ** DECIMALS) / 10 ** DECIMALS;
}

// Equirectangular projection onto a 360x180 viewBox: lon [-180,180] -> x [0,360], lat [90,-90] -> y [0,180]
function project([lon, lat]) {
  return [round(lon + 180), round(90 - lat)];
}

// Splits a ring wherever it crosses the antimeridian (lon jumps by >180°
// between consecutive points, e.g. Russia/Fiji), interpolating the latitude
// at the crossing and closing/reopening the subpath at the map edge (x=0/360)
// instead of drawing a straight line clear across the map.
function ringToPath(ring) {
  const segments = [[]];
  let prevRaw = null;

  for (const point of ring) {
    const [lon, lat] = point;
    if (prevRaw) {
      const [prevLon, prevLat] = prevRaw;
      const delta = lon - prevLon;
      if (delta > 180 || delta < -180) {
        const crossingLon = delta > 180 ? -180 : 180;
        const otherSideLon = delta > 180 ? 180 : -180;
        const unwrappedLon = delta > 180 ? lon - 360 : lon + 360;
        const denom = unwrappedLon - prevLon;
        // denom is 0 when prevLon already sits exactly on the boundary (source
        // data sometimes double-emits the ±180 point) — the crossing is prevRaw itself.
        const t = denom === 0 ? 0 : (crossingLon - prevLon) / denom;
        const crossingLat = prevLat + (lat - prevLat) * t;
        segments[segments.length - 1].push([crossingLon, crossingLat]);
        segments.push([[otherSideLon, crossingLat]]);
      }
    }
    segments[segments.length - 1].push(point);
    prevRaw = point;
  }

  return segments
    .filter((seg) => seg.length > 1)
    .map(
      (seg) =>
        seg
          .map(([lon, lat], i) => {
            const [x, y] = project([lon, lat]);
            return `${i === 0 ? 'M' : 'L'}${x},${y}`;
          })
          .join('') + 'Z'
    )
    .join('');
}

function geometryToPath(geometry) {
  if (geometry.type === 'Polygon') {
    return geometry.coordinates.map(ringToPath).join('');
  }
  if (geometry.type === 'MultiPolygon') {
    return geometry.coordinates.map((polygon) => polygon.map(ringToPath).join('')).join('');
  }
  return '';
}

const collection = topojson.feature(topology, topology.objects.countries);

const seen = new Map(); // iso alpha-2 -> path 'd' (merge multi-part features that share an id, e.g. France + overseas)
const skipped = [];

for (const feature of collection.features) {
  const numeric = String(feature.id).padStart(3, '0');
  const alpha2 = iso.numericToAlpha2(numeric);
  if (!alpha2) {
    skipped.push({ id: feature.id, name: feature.properties?.name });
    continue;
  }
  const d = geometryToPath(feature.geometry);
  if (!d) continue;
  seen.set(alpha2, (seen.get(alpha2) || '') + d);
}

const entries = Array.from(seen.entries())
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([code, d]) => ({ code, d }));

const header = `// Generated by scripts/generate-world-map.js — do not hand-edit.
// Source: world-atlas countries-110m (Natural Earth, public domain).
// Equirectangular projection, viewBox "0 0 360 180". One entry per ISO 3166-1 alpha-2 code.

export interface WorldCountryPath {
  code: string;
  d: string;
}

export const WORLD_MAP_VIEWBOX = '0 0 360 180';

export const WORLD_COUNTRY_PATHS: WorldCountryPath[] = ${JSON.stringify(entries)};
`;

const outPath = path.join(__dirname, '..', 'src', 'data', 'worldCountryPaths.ts');
fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, header);

console.log(`Wrote ${entries.length} country paths to ${outPath}`);
if (skipped.length) {
  console.log(`Skipped ${skipped.length} features with no ISO alpha-2 match:`, skipped.map((s) => s.name).join(', '));
}
console.log(`Output size: ${(fs.statSync(outPath).size / 1024).toFixed(1)} KB`);
